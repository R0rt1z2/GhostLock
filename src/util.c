#define BUDDY_DRAIN_MAX 1024
void groom_tunables_init(void) {
  const char *e;
  if ((e = getenv("IONSTACK_DRAIN"))) {
    int v = atoi(e);
    if (v > 0 && v <= BUDDY_DRAIN_MAX) g_buddy_drain = v;
  }
  if ((e = getenv("IONSTACK_MM_PARTIALS"))) {
    int v = atoi(e);
    if (v > 0 && v <= 64) g_mm_partials = v;
  }
  if ((e = getenv("IONSTACK_CORE"))) {
    int v = atoi(e);
    if (v >= 0 && v < 32) g_core = v;
  }
  pr_success("Groom tunables: drain=%d mm_partials=%d core=%d "
             "mm_order=%d mm_sz=0x%x\n",
             g_buddy_drain, g_mm_partials, g_core, MM_ORDER, MM_STRUCT_SZ);
}
